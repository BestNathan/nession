#!/usr/bin/env node
// #2319: signed staging Developer dispatch. Trusted main-owned code signs one
// exact authenticated staging tip for the registered dev-qwen-01 Claude Code
// Developer. The staging model executor never receives this HMAC key; it only
// consumes the already-verified artifact identity produced by a separate
// trusted job.
//
// The staging lane reuses the registry's `dev-claude-qwen` Environment and
// model token. The signed body pins the model and CLI version resolved at
// signing time, so a later Environment/default change cannot alter an already
// dispatched task. The registry still owns the role/provider binding.
import {createHash, createHmac, timingSafeEqual} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {verifyStagingDeveloperSource} from './staging-developer-source.mjs';
import {readWorkerZipMember} from './worker-zip.mjs';

const REPO='BestNathan/nession';
const ISSUE=2319;
const KIND='staging_developer_dispatch';
const ENVIRONMENT='dev-claude-qwen';
const AGENT='dev-qwen-01', ROLE='developer', TASK='implement', PROVIDER='claude-code';
const SHA=/^[a-f0-9]{40}$/;
const HEX64=/^[a-f0-9]{64}$/;
const DIGEST=/^sha256:[a-f0-9]{64}$/;
const QWEN=/^qwen[a-z0-9._-]*$/i;
const VERSION=/^\d+\.\d+\.\d+(?:[-+][A-Za-z0-9.-]+)?$/;
const KEY_ID=/^[a-z][a-z0-9-]{1,63}$/;
const MAX_TTL_MS=15*60*1000;
const ENVELOPE=['body','kind','schema_version','signature'];
const PHASES=['seed','resume'];
const CHECKPOINT_FIELDS=['version','commit_sha','ciphertext_sha256',
  'seed_run_id','seed_attempt'];
const CORE_SEED=['schema_version','kind','repository','issue','target_sha','agent_id',
  'role','task','provider','environment','model','cli_version','phase',
  'default_model','source_run_id','source_run_attempt','source_artifact_id',
  'source_artifact_digest','issuer_run_id','issued_at','expires_at','key_id'];
const CORE_RESUME=[...CORE_SEED,'checkpoint'];

function fail(message){throw new Error('Staging Developer dispatch: '+message);}
function positive(value){return Number.isSafeInteger(value)&&value>0;}
function own(value,fields){
  return value&&typeof value==='object'&&!Array.isArray(value)&&
    Object.keys(value).every(key=>fields.includes(key));
}
function exact(value,fields){
  return own(value,fields)&&Object.keys(value).length===fields.length;
}
function canonical(value){
  return JSON.stringify(Object.fromEntries(Object.keys(value).sort().map(key=>[key,value[key]])));
}
function keyBytes(key){
  if(!Buffer.isBuffer(key)||key.length<32)fail('signing key must be at least 32 bytes');
  return key;
}
function mac(key,value){return createHmac('sha256',keyBytes(key)).update(value).digest();}
function dispatchId(core){
  return createHash('sha256').update(canonical(core)).digest('hex');
}

// A staging-only HMAC secret is generated by the operator and stored in the
// dedicated `agent-staging-controller` Environment. It is never derived from
// the production Store Writer key.
export function parseStagingDispatchKey(value){
  if(typeof value!=='string'||!/^[a-f0-9]{64}$/i.test(value))
    fail('staging dispatch key must be 64 hex characters');
  return Buffer.from(value,'hex');
}

function stagedIdentity(registry){
  const instance=registry?.instances?.[AGENT];
  if(!instance||instance.role!==ROLE||instance.provider!==PROVIDER)
    fail('dev-qwen-01 is not a registered Claude Code Developer');
}
function validCheckpoint(checkpoint){
  return exact(checkpoint,CHECKPOINT_FIELDS)&&
    positive(checkpoint.version)&&SHA.test(checkpoint.commit_sha??'')&&
    HEX64.test(checkpoint.ciphertext_sha256??'')&&
    positive(checkpoint.seed_run_id)&&checkpoint.seed_attempt===1;
}
function coreFields(phase){
  if(!PHASES.includes(phase))fail('invalid staging dispatch phase');
  return phase==='resume'?CORE_RESUME:CORE_SEED;
}

function validCore(body,registry){
  const phase=body?.phase;
  const fields=coreFields(phase);
  if(!exact(body,['dispatch_id',...fields])||
      body.schema_version!==1||body.kind!==KIND||body.repository!==REPO||
      body.issue!==ISSUE||!SHA.test(body.target_sha??'')||
      body.agent_id!==AGENT||body.role!==ROLE||body.task!==TASK||
      body.provider!==PROVIDER||body.environment!==ENVIRONMENT||
      !QWEN.test(body.model??'')||!QWEN.test(body.default_model??'')||
      !VERSION.test(body.cli_version??'')||
      !positive(body.source_run_id)||body.source_run_attempt!==1||
      !positive(body.source_artifact_id)||
      !DIGEST.test(body.source_artifact_digest??'')||
      !positive(body.issuer_run_id)||!Number.isSafeInteger(body.issued_at)||
      !Number.isSafeInteger(body.expires_at)||
      body.expires_at<=body.issued_at||
      body.expires_at-body.issued_at>MAX_TTL_MS||
      !KEY_ID.test(body.key_id??'')||!HEX64.test(body.dispatch_id??'')||
      (phase==='resume'?!validCheckpoint(body.checkpoint):
        Object.hasOwn(body,'checkpoint')))
    fail('invalid staging dispatch body');
  stagedIdentity(registry);
  return body;
}

export function buildStagingDeveloperDispatch({
  admission,registry,signer,now=Date.now(),ttlMs=10*60*1000,
  phase='seed',checkpoint=null,
}){
  // Shape produced by the trusted staging-developer-source verifier.
  if(!exact(admission,['target_sha','source_sha','source_run_id',
      'source_run_attempt','artifact_id','artifact_digest','verified_proof'])||
      !SHA.test(admission.target_sha??'')||!SHA.test(admission.source_sha??'')||
      !positive(admission.source_run_id)||admission.source_run_attempt!==1||
      !positive(admission.artifact_id)||
      !DIGEST.test(admission.artifact_digest??'')||
      admission.verified_proof!=='synthetic_worker_canary_only')
    fail('admission is not an exact authenticated staging source');
  stagedIdentity(registry);
  if(!signer||!KEY_ID.test(signer.key_id??'')||!positive(signer.issuer_run_id)||
      !QWEN.test(signer.model??'')||!QWEN.test(signer.default_model??'')||
      !VERSION.test(signer.cli_version??''))
    fail('invalid staging dispatch signer');
  if(!Number.isSafeInteger(now)||!Number.isSafeInteger(ttlMs)||
      ttlMs<1000||ttlMs>MAX_TTL_MS) fail('invalid staging dispatch TTL');
  coreFields(phase);
  if(phase==='seed'&&checkpoint!==null)
    fail('seed dispatch must not carry a checkpoint');
  if(phase==='resume'&&!validCheckpoint(checkpoint))
    fail('resume dispatch requires an exact checkpoint commitment');
  const core={schema_version:1,kind:KIND,repository:REPO,issue:ISSUE,
    target_sha:admission.target_sha,agent_id:AGENT,role:ROLE,task:TASK,
    provider:PROVIDER,environment:ENVIRONMENT,phase,
    model:signer.model,default_model:signer.default_model,
    cli_version:signer.cli_version,
    source_run_id:admission.source_run_id,
    source_run_attempt:admission.source_run_attempt,
    source_artifact_id:admission.artifact_id,
    source_artifact_digest:admission.artifact_digest,
    issuer_run_id:signer.issuer_run_id,issued_at:now,expires_at:now+ttlMs,
    key_id:signer.key_id,
    ...(phase==='resume'?{checkpoint}:{})};
  const body={...core,dispatch_id:dispatchId(core)};
  validCore(body,registry);
  return Object.freeze({schema_version:1,kind:KIND,body,
    signature:mac(signer.key,canonical(body)).toString('hex')});
}

export function verifyStagingDeveloperDispatch({
  record,keyring,admission,registry,now=Date.now(),
}){
  if(!exact(record,ENVELOPE)||record.schema_version!==1||record.kind!==KIND||
      typeof record.signature!=='string'||!/^[a-f0-9]{64}$/.test(record.signature))
    fail('invalid staging dispatch envelope');
  const body=validCore(record.body,registry);
  const core=Object.fromEntries(coreFields(body.phase).map(key=>[key,body[key]]));
  if(body.dispatch_id!==dispatchId(core))fail('staging dispatch identity mismatch');
  if(!keyring||typeof keyring!=='object'||Array.isArray(keyring)||
      Object.keys(keyring).length===0)fail('invalid staging keyring');
  const key=keyring[body.key_id];
  if(!key)fail('unknown staging signing key');
  const expected=mac(key,canonical(body));
  const actual=Buffer.from(record.signature,'hex');
  if(actual.length!==expected.length||!timingSafeEqual(expected,actual))
    fail('invalid staging dispatch signature');
  if(now<body.issued_at-30000||now>body.expires_at)
    fail('staging dispatch outside validity window');
  // The signed body must describe exactly the independently authenticated
  // admission; neither artifact may substitute for the other.
  if(!admission||admission.target_sha!==body.target_sha||
      admission.source_run_id!==body.source_run_id||
      admission.source_run_attempt!==body.source_run_attempt||
      admission.artifact_id!==body.source_artifact_id||
      admission.artifact_digest!==body.source_artifact_digest)
    fail('staging dispatch does not match the authenticated admission');
  return Object.freeze({...body});
}

export const STAGING_DISPATCH_ISSUE=ISSUE;
export const STAGING_DISPATCH_ENVIRONMENT=ENVIRONMENT;

const REPO_NAME=REPO;
const DISPATCH_WORKFLOW={
  path:'.github/workflows/acceptance-staging-developer-dispatch.yml',
  name:'Acceptance / Staging Developer Dispatch',
};
const ZIP_DIGEST=/^sha256:[a-f0-9]{64}$/;

// Authenticate the signed dispatch GitHub Run/Artifact and return its bounded
// record. The admission locator inside the record is still untrusted until the
// dispatch HMAC and independent admission authentication both succeed.
export function readStagingDeveloperDispatchArtifact({
  dispatchRun,dispatchArtifacts,dispatchZip,
}) {
  if(!dispatchRun||!Number.isSafeInteger(dispatchRun.id)||dispatchRun.id<1||
      dispatchRun.run_attempt!==1||
      dispatchRun.path!==DISPATCH_WORKFLOW.path||
      dispatchRun.name!==DISPATCH_WORKFLOW.name||
      !['workflow_run','workflow_dispatch'].includes(dispatchRun.event)||
      (dispatchRun.event==='workflow_dispatch'&&
        dispatchRun.actor?.login!=='BestNathan')||
      dispatchRun.head_branch!=='main'||
      dispatchRun.repository?.full_name!==REPO_NAME||
      dispatchRun.head_repository?.full_name!==REPO_NAME||
      dispatchRun.status!=='completed'||dispatchRun.conclusion!=='success')
    fail('untrusted or incomplete staging dispatch Run');
  if(!dispatchArtifacts||!Array.isArray(dispatchArtifacts.artifacts)||
      !Number.isInteger(dispatchArtifacts.total_count)||
      dispatchArtifacts.total_count<0||dispatchArtifacts.total_count>100||
      dispatchArtifacts.artifacts.length!==dispatchArtifacts.total_count)
    fail('unbounded or incomplete dispatch artifact listing');
  const name='staging-developer-dispatch-'+dispatchRun.id+'-'+
    dispatchRun.run_attempt;
  const matches=dispatchArtifacts.artifacts.filter(a=>a.name===name);
  if(matches.length!==1||matches[0].expired!==false||
      !Number.isSafeInteger(matches[0].id)||matches[0].id<1||
      matches[0].workflow_run?.id!==dispatchRun.id||
      matches[0].workflow_run?.head_sha!==dispatchRun.head_sha||
      !ZIP_DIGEST.test(matches[0].digest??''))
    fail('missing/ambiguous authenticated dispatch artifact');
  if(!Buffer.isBuffer(dispatchZip)||dispatchZip.length>256*1024||
      'sha256:'+createHash('sha256').update(dispatchZip).digest('hex')!==
        matches[0].digest)
    fail('dispatch ZIP differs from GitHub-authenticated digest');
  let record;
  try{record=JSON.parse(readWorkerZipMember(dispatchZip,
    'staging-developer-dispatch.json').toString('utf8'));}
  catch{fail('invalid bounded staging dispatch member');}
  return Object.freeze({record,artifact_id:matches[0].id,
    artifact_digest:matches[0].digest});
}

// The staging Worker's trusted pre-model job runs this. It authenticates the
// dispatch GitHub Run/Artifact and independently re-authenticates the upstream
// admission before releasing the exact staging SHA to the model executor.
export function verifyStagingDeveloperDispatchArtifact({
  dispatchRun,dispatchArtifacts,dispatchZip,
  admissionRun,admissionArtifacts,admissionZip,
  keyring,registry,now=Date.now(),
}) {
  const {record,artifact_id,artifact_digest}=readStagingDeveloperDispatchArtifact({
    dispatchRun,dispatchArtifacts,dispatchZip});
  // The admission identity inside the dispatch is a locator only; it is
  // re-authenticated independently below.
  const sourceRunId=record?.body?.source_run_id;
  const sourceAttempt=record?.body?.source_run_attempt;
  if(admissionRun?.id!==sourceRunId||admissionRun?.run_attempt!==sourceAttempt)
    fail('dispatch points at a different admission Run');
  const admission=verifyStagingDeveloperSource({
    run:admissionRun,artifacts:admissionArtifacts,zip:admissionZip});
  const body=verifyStagingDeveloperDispatch({record,keyring,admission,registry,now});
  return Object.freeze({dispatch_id:body.dispatch_id,target_sha:body.target_sha,
    source_main_sha:admission.source_sha,phase:body.phase,
    model:body.model,default_model:body.default_model,
    checkpoint:body.checkpoint??null,
    agent_id:body.agent_id,role:body.role,provider:body.provider,
    cli_version:body.cli_version,
    environment:body.environment,source_run_id:body.source_run_id,
    source_run_attempt:body.source_run_attempt,issuer_run_id:body.issuer_run_id,
    artifact_id,artifact_digest,
    admission_artifact_id:admission.artifact_id,
    admission_artifact_digest:admission.artifact_digest});
}

function readJson(file){
  const stat=fs.lstatSync(file);
  if(!stat.isFile()||stat.isSymbolicLink()||stat.size>1024*1024)
    fail('unsafe staging dispatch input');
  return JSON.parse(fs.readFileSync(file,'utf8'));
}
